#!/bin/bash
# Regenerates server/src/prompts.ts from the app's prompts. Run after changing any system prompt,
# then redeploy the Worker, or the proxy will reject the new prompt.
set -euo pipefail
cd "$(dirname "$0")/.."
swift build -c release --product hushtype-cli >/dev/null
{ echo "// Generated by Scripts/sync_prompts.sh — do not edit."; echo -n "export const PROMPT_PREFIXES: string[] = "; .build/release/hushtype-cli prompts; echo ";"; } > server/src/prompts.ts
echo "server/src/prompts.ts updated"
